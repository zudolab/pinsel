// Writes src/preview/styles.generated.ts: the approved pinsel-ui CSS as one
// string the Worker inlines into preview documents. Runs with
// `pnpm content:assemble` (root) and before the Worker's own checks.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const stylesDir = join(here, "../../../packages/pinsel-ui/styles");
const files = ["tokens.css", "colors.css", "components.css"];
const css = (await Promise.all(files.map((name) => readFile(join(stylesDir, name), "utf8")))).join("\n");
const out = join(here, "../src/preview/styles.generated.ts");
await mkdir(dirname(out), { recursive: true });
await writeFile(out, `// Generated by scripts/generate-preview-styles.mjs from packages/pinsel-ui/styles/{${files.join(",")}}; do not edit.\nexport const PREVIEW_STYLES = ${JSON.stringify(css)};\n`);
console.log(`generate-preview-styles wrote ${out} (${css.length} chars)`);
