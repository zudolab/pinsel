// Mirrors every `packages/pinsel-ui/src/**/<name>.stories.tsx` as
// `apps/styleguide/ui/<name>/<name>.stories.tsx`, a two-line re-export.
// zfb refuses a collection root that escapes the project (`..`), and the
// engine derives its `componentDocs` collection from `componentsRoots.dir`,
// so the stories root must live inside this app while the stories themselves
// stay co-located with their components. Usage: node scripts/gen-story-shims.mjs [--check]
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const uiSrc = path.resolve(app, "../../packages/pinsel-ui/src");
const out = path.join(app, "ui");
const check = process.argv.includes("--check");

async function stories(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await stories(full)));
    else if (entry.name.endsWith(".stories.tsx")) found.push(full);
  }
  return found.sort();
}

const expected = new Map();
for (const file of await stories(uiSrc)) {
  const relative = path.relative(uiSrc, file).split(path.sep).join("/");
  const name = path.basename(file, ".stories.tsx");
  const specifier = `@pinsel/ui/src/${relative}`;
  expected.set(
    `${name}/${name}.stories.tsx`,
    `// Generated by scripts/gen-story-shims.mjs; do not edit. The story lives next to its component.\nexport * from "${specifier}";\nexport { default } from "${specifier}";\n`,
  );
}

const existing = new Map();
try {
  for (const file of await stories(out)) existing.set(path.relative(out, file).split(path.sep).join("/"), await readFile(file, "utf8"));
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}

const stale = [...existing.keys()].filter((key) => !expected.has(key));
const changed = [...expected].filter(([key, content]) => existing.get(key) !== content).map(([key]) => key);
if (check) {
  if (stale.length === 0 && changed.length === 0) {
    console.log(`OK — ${expected.size} story shim(s) are up to date.`);
    process.exit(0);
  }
  console.error(`story shims are out of date: ${[...changed.map((key) => `changed ${key}`), ...stale.map((key) => `stale ${key}`)].join(", ")}; run pnpm --filter styleguide gen-story-shims`);
  process.exit(1);
}
for (const key of stale) await rm(path.join(out, key));
for (const key of changed) {
  await mkdir(path.dirname(path.join(out, key)), { recursive: true });
  await writeFile(path.join(out, key), expected.get(key));
}
console.log(`Wrote ${changed.length} story shim(s) (${expected.size} total, ${stale.length} removed) to ${path.relative(app, out)}/`);
