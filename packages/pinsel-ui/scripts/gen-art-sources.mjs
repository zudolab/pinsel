// Writes src/art-window/art-sources.generated.ts: the four approved SVGs from
// src/art/ as string constants, so every consumer (zfb SSR, the Worker bundle,
// vitest) inlines them without an `.svg` loader. The SVG files stay the
// byte-exact source of truth (`pnpm assets:verify`); `--check` fails when the
// module no longer matches them. Usage: node scripts/gen-art-sources.mjs [--check]
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src/art-window/art-sources.generated.ts");
const names = ["hero", "middle", "closing", "shallow"];

let body = "// Generated by scripts/gen-art-sources.mjs from src/art/*.svg; do not edit.\n";
body += "export const ART_SOURCES = {\n";
for (const name of names) {
  const svg = await readFile(path.join(root, `src/art/water-paper-${name}.svg`), "utf8");
  body += `  ${name}: ${JSON.stringify(svg)},\n`;
}
body += "} as const;\n";

if (process.argv.includes("--check")) {
  const current = await readFile(out, "utf8").catch(() => "");
  if (current !== body) {
    console.error("src/art-window/art-sources.generated.ts is out of date; run pnpm --filter @pinsel/ui gen:art");
    process.exit(1);
  }
  console.log("OK — art sources are up to date.");
} else {
  await writeFile(out, body);
  console.log(`Wrote ${path.relative(root, out)}`);
}
