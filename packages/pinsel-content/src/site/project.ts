// `pnpm content:project [--snapshot <file>]`: compile the assembled project
// (or a saved snapshot's project) with the Node release compiler and write the
// derived route documents, page metadata and navigation the ZFB site renders.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import type { TrustedComponentPack } from "@zudo-composer/component-contract";
import { stripSiteBuildModules } from "zudo-composer/content";
import { compileStaticSite } from "zudo-composer/site-build";
import type { ContentEntryRecord, SiteProject } from "zudo-composer/site-project";

import { NAV_HREFS, PINSEL_ROUTES, outputFileForRoute, planPathname } from "../invariants";
import { fieldId } from "../models";
import { PINSEL_CONTENT_PROVIDER_ID } from "../models/define";
import { REPO_ROOT, SITE_PROJECT_DIR, SITE_PROJECT_PATH } from "./entries";
import { structurePack } from "./pack";
import { resolveAllPageMeta } from "./page-meta";
import { HEADER_NAV_ORDER } from "./structure";

export const ROUTES_OUT = join(REPO_ROOT, "apps/site/data/routes.generated.ts");
export const NAVIGATION_OUT = join(REPO_ROOT, "apps/site/data/navigation.generated.ts");
export const PLAN_OUT = join(SITE_PROJECT_DIR, "plan.json");

export type ProjectedPlan = ReturnType<typeof stripSiteBuildModules>;

export interface Projection {
  projectSourceRevision: string;
  plan: ProjectedPlan;
  entries: readonly ContentEntryRecord[];
}

/** compileStaticSite (throws on any blocking diagnostic) → the portable plan, plus the entries the project carries. */
export async function projectSite(projectPath: string, pack: TrustedComponentPack): Promise<Projection> {
  const compiled = await compileStaticSite({ projectPath, pack, assetsStoreRoot: join(SITE_PROJECT_DIR, "assets") });
  const plan = stripSiteBuildModules(compiled.build);
  const pathnames = plan.routes.map((route) => route.pathname);
  const missing = PINSEL_ROUTES.filter((route) => !pathnames.includes(planPathname(route)));
  if (missing.length > 0 || pathnames.length !== PINSEL_ROUTES.length) throw new Error(`compiled routes ${JSON.stringify(pathnames)} do not match the 14 outputs (missing ${JSON.stringify(missing)})`);
  const project = compiled.project as SiteProject;
  const entries = project.providers.content.find((provider) => provider.id === PINSEL_CONTENT_PROVIDER_ID)?.entries ?? [];
  return { projectSourceRevision: compiled.projectSourceRevision, plan, entries };
}

const text = (entry: ContentEntryRecord | undefined, key: string) => String(entry?.values[fieldId("nav-link", key)] ?? "");

/** Header (prototype order) and footer (`nav-link.order`) links as rendered, for consumers outside the route documents. */
export function navigationFromEntries(entries: readonly ContentEntryRecord[]) {
  const links = entries.filter((entry) => entry.modelId === "nav-link");
  const byHref = (href: string) => links.find((entry) => entry.values[fieldId("nav-link", "href")] === href);
  const footer = [...links].sort((left, right) => Number(left.values[fieldId("nav-link", "order")]) - Number(right.values[fieldId("nav-link", "order")]));
  return {
    header: HEADER_NAV_ORDER.map((href) => ({ href, label: text(byHref(href), "headerLabel") })),
    footer: footer.map((entry) => ({ href: text(entry, "href"), label: text(entry, "label"), title: text(entry, "footerTitle"), description: text(entry, "footerDescription") })),
    hrefs: [...NAV_HREFS],
  };
}

export function routesModule(projection: Projection, source: string): string {
  const meta = resolveAllPageMeta(projection.entries);
  const outputs = PINSEL_ROUTES.map((route) => ({ route, pathname: planPathname(route), file: outputFileForRoute(route), ...meta[route] }));
  return [
    `// Generated by \`pnpm content:project\`; do not edit. Source: ${source}`,
    'import type { RouteDocument } from "@pinsel/ui";',
    "",
    `export const PROJECT_SOURCE_REVISION = ${JSON.stringify(projection.projectSourceRevision)};`,
    "",
    "/** The 14 outputs: approved route, compiled plan pathname, output file and <title>/description from Content. */",
    `export const OUTPUTS: readonly { route: string; pathname: string; file: string; title: string; description: string }[] = ${JSON.stringify(outputs, null, 2)};`,
    "",
    `export const ROUTES: readonly RouteDocument[] = ${JSON.stringify(projection.plan.routes, null, 2)};`,
    "",
  ].join("\n");
}

export function navigationModule(projection: Projection, source: string): string {
  const navigation = navigationFromEntries(projection.entries);
  return [
    `// Generated by \`pnpm content:project\`; do not edit. Source: ${source}`,
    `export const HEADER_NAV: readonly { href: string; label: string }[] = ${JSON.stringify(navigation.header, null, 2)};`,
    "",
    `export const FOOTER_NAV: readonly { href: string; label: string; title: string; description: string }[] = ${JSON.stringify(navigation.footer, null, 2)};`,
    "",
    `export const SITEMAP_NAVIGATION = ${JSON.stringify(projection.plan.navigation, null, 2)} as const;`,
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const snapshotIndex = process.argv.indexOf("--snapshot");
  let projectPath = SITE_PROJECT_PATH;
  if (snapshotIndex !== -1) {
    // A snapshot record from the authoring Worker: `{ snapshotId, project, … }`.
    const snapshotFile = process.argv[snapshotIndex + 1];
    if (!snapshotFile) throw new Error("--snapshot needs a file path");
    const record = JSON.parse(await readFile(snapshotFile, "utf8")) as { snapshotId?: string; project?: unknown };
    if (!record.project || typeof record.snapshotId !== "string") throw new Error(`${snapshotFile} is not a snapshot record`);
    projectPath = join(SITE_PROJECT_DIR, `snapshot-${record.snapshotId}.json`);
    await mkdir(SITE_PROJECT_DIR, { recursive: true });
    await writeFile(projectPath, `${JSON.stringify(record.project)}\n`);
  }
  const projection = await projectSite(projectPath, structurePack());
  const source = snapshotIndex === -1 ? "packages/pinsel-content/.site-project/site-project.json" : `snapshot ${projectPath}`;
  await mkdir(join(REPO_ROOT, "apps/site/data"), { recursive: true });
  await writeFile(PLAN_OUT, `${JSON.stringify({ projectSourceRevision: projection.projectSourceRevision, plan: projection.plan }, null, 2)}\n`);
  await writeFile(ROUTES_OUT, routesModule(projection, source));
  await writeFile(NAVIGATION_OUT, navigationModule(projection, source));
  console.log(`content:project compiled ${projection.plan.routes.length} route(s) from ${projectPath} -> ${ROUTES_OUT}, ${NAVIGATION_OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
